// Generates the flavor capability map: a machine-readable diff of what the
// loxilb-inference-gateway API surface adds over upstream loxilb, computed
// from the vendored specs in api-spec/. The UI's flavor gating (nav items,
// form groups, enum option filtering) reads this map instead of hand-kept
// lists, so re-vendoring a spec is the ONLY step needed to refresh gating —
// the loxilb ⊆ gateway relationship itself is enforced by
// src/api/loxilb-subset.contract.test.ts.
//
// Usage:  npm run gen:api   (part of the chain; writes src/api/gen/)
//
// Output is deterministic (sorted, no timestamps) so `gen:api:check` can
// diff it in CI.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import YAML from 'yaml';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = f => YAML.parse(fs.readFileSync(path.join(root, f), 'utf8'));

const loxilb = read('api-spec/loxilb-swagger.yml');
const gateway = read('api-spec/gateway-swagger.yml');

function resolveRef(spec, node) {
	if (node && node.$ref) {
		const parts = node.$ref.replace(/^#\//, '').split('/');
		return resolveRef(spec, parts.reduce((acc, k) => acc?.[k], spec));
	}
	return node;
}

// ---- paths & methods ------------------------------------------------------
const gatewayOnlyPaths = Object.keys(gateway.paths ?? {})
	.filter(p => !loxilb.paths?.[p])
	.sort();

const gatewayOnlyMethods = {};
for (const [p, ops] of Object.entries(gateway.paths ?? {})) {
	if (!loxilb.paths?.[p]) continue;
	const extra = Object.keys(ops).filter(m => m !== 'parameters' && !loxilb.paths[p][m]).sort();
	if (extra.length) gatewayOnlyMethods[p] = extra;
}

// ---- query/path parameters on shared operations ---------------------------
const gatewayOnlyParams = {};
for (const [p, ops] of Object.entries(gateway.paths ?? {})) {
	for (const [method, op] of Object.entries(ops)) {
		if (method === 'parameters' || !loxilb.paths?.[p]?.[method]) continue;
		const lNames = new Set((loxilb.paths[p][method].parameters ?? []).map(q => `${q.in}:${q.name}`));
		const extra = (op.parameters ?? [])
			.filter(q => q.in !== 'body' && !lNames.has(`${q.in}:${q.name}`))
			.map(q => `${q.in}:${q.name}`)
			.sort();
		if (extra.length) gatewayOnlyParams[`${method.toUpperCase()} ${p}`] = extra;
	}
}

// ---- fields & enum values inside shared definitions (recursive) -----------
const gatewayOnlyFields = {};
const gatewayOnlyEnumValues = {};
function walk(lNode, gNode, ctx, seen) {
	if (lNode?.$ref || gNode?.$ref) {
		const key = `${lNode?.$ref ?? ''}=>${gNode?.$ref ?? ''}`;
		if (seen.has(key)) return;
		seen.add(key);
	}
	const l = resolveRef(loxilb, lNode);
	const g = resolveRef(gateway, gNode);
	if (!l || !g) return;
	if (Array.isArray(l.enum) && Array.isArray(g.enum)) {
		const extra = g.enum.filter(v => !l.enum.includes(v));
		if (extra.length) gatewayOnlyEnumValues[ctx] = extra;
	}
	const extraProps = Object.keys(g.properties ?? {}).filter(k => !(l.properties ?? {})[k]).sort();
	if (extraProps.length) gatewayOnlyFields[ctx] = extraProps;
	for (const [name, prop] of Object.entries(l.properties ?? {})) {
		if (g.properties?.[name]) walk(prop, g.properties[name], `${ctx}.${name}`, seen);
	}
	if (l.items && g.items) walk(l.items, g.items, `${ctx}[]`, seen);
}
const seen = new Set();
const sharedDefs = Object.keys(loxilb.definitions ?? {}).filter(d => gateway.definitions?.[d]).sort();
for (const d of sharedDefs) walk(loxilb.definitions[d], gateway.definitions[d], d, seen);

const gatewayOnlyDefinitions = Object.keys(gateway.definitions ?? {})
	.filter(d => !loxilb.definitions?.[d])
	.sort();

// ---- provenance (from SOURCES.json, no fresh timestamps → deterministic) --
const sources = JSON.parse(fs.readFileSync(path.join(root, 'api-spec/SOURCES.json'), 'utf8'));

const map = {
	'//': 'Generated by scripts/gen-capability-map.mjs from api-spec/*.yml — DO NOT EDIT. Regenerate with: npm run gen:api',
	sources: {
		loxilb: sources.loxilb?.commit ?? 'unknown',
		gateway: sources.gateway?.commit ?? 'unknown',
	},
	gatewayOnlyPaths,
	gatewayOnlyMethods,
	gatewayOnlyParams,
	gatewayOnlyFields,
	gatewayOnlyEnumValues,
	gatewayOnlyDefinitions,
};

const out = 'src/api/gen/loxilb-capability-map.json';
fs.writeFileSync(path.join(root, out), JSON.stringify(map, null, '\t') + '\n');
console.log(
	`generated ${out}: ${gatewayOnlyPaths.length} gateway-only paths, ` +
	`${Object.keys(gatewayOnlyFields).length} field sites, ` +
	`${Object.keys(gatewayOnlyEnumValues).length} enum sites`,
);
